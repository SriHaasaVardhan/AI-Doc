"use client";

import { useState, useEffect } from "react";
import { useRouter } from "next/navigation";
import { motion } from "framer-motion";
import { globalStore } from "@/lib/store";
import { FloatingOrbs } from "@/components/ui/FloatingOrbs";
import { AnimatedButton } from "@/components/ui/AnimatedButton";
import { DocTabs } from "@/components/results/DocTabs";
import { MarkdownPreview } from "@/components/results/MarkdownPreview";
import { HealthDashboard } from "@/components/results/HealthDashboard";
import { InsightsPanel } from "@/components/results/InsightsPanel";
import { ChatInterface } from "@/components/results/ChatInterface";
import { ExportModal } from "@/components/results/ExportModal";

const DOC_CONTENT_KEYS = [
  "readme",
  "api-docs",
  "setup-guide",
  "architecture",
  "folder-structure",
  "mermaid-diagrams",
] as const;

export default function ResultsPage() {
  const router = useRouter();
  const [activeTab, setActiveTab] = useState("readme");
  const [exportModalOpen, setExportModalOpen] = useState(false);

  const summary = globalStore.getSummary();
  const docs = globalStore.getGenerationResult();
  const health = globalStore.getHealthAnalysis();
  const insights = globalStore.getInsights();

  useEffect(() => {
    if (!summary || !docs) {
      router.push("/");
    }
  }, [summary, docs, router]);

  if (!summary || !docs) return null;

  const docContentByTab: Record<(typeof DOC_CONTENT_KEYS)[number], string> = {
    readme: docs.readme,
    "api-docs": docs.apiDocs,
    "setup-guide": docs.setupGuide,
    architecture: docs.architecture,
    "folder-structure": docs.folderStructure,
    "mermaid-diagrams": docs.mermaidDiagrams,
  };

  const availableDocs = DOC_CONTENT_KEYS.filter((key) => !!docContentByTab[key]);

  const renderContent = () => {
    if (activeTab === "health" && health) {
      return <HealthDashboard health={health} />;
    }
    if (activeTab === "insights" && insights) {
      return <InsightsPanel insights={insights} />;
    }
    if (activeTab === "chat") {
      return (
        <ChatInterface
          summaryData={summary}
          generatedDocs={{
            readme: docs.readme,
            setupGuide: docs.setupGuide,
            architecture: docs.architecture,
            apiDocs: docs.apiDocs,
          }}
        />
      );
    }
    
    // Default to markdown preview for docs
    const content = docContentByTab[activeTab as keyof typeof docContentByTab] || "";
    return <MarkdownPreview content={content} />;
  };

  return (
    <div className="min-h-screen pt-24 pb-12 px-6 flex flex-col max-w-7xl mx-auto relative">
      <FloatingOrbs />
      
      <ExportModal 
        isOpen={exportModalOpen} 
        onClose={() => setExportModalOpen(false)} 
        docs={docContentByTab}
        repoName={summary.name}
      />

      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
      >
        <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4 mb-8">
          <div>
            <h1 className="text-3xl font-bold text-white mb-2">{summary.name}</h1>
            <div className="flex flex-wrap gap-2 text-sm text-zinc-400">
              <span className="px-2 py-1 rounded-md bg-white/5 border border-white/10">
                {summary.totalFiles} files
              </span>
              <span className="px-2 py-1 rounded-md bg-white/5 border border-white/10">
                {summary.totalLines} lines
              </span>
              <span className="px-2 py-1 rounded-md bg-white/5 border border-white/10 text-blue-400 flex items-center gap-1">
                <span className="w-2 h-2 rounded-full bg-blue-500 animate-pulse" />
                Generated by {docs.provider}
              </span>
            </div>
          </div>
          
          <div className="flex gap-3">
            <AnimatedButton onClick={() => router.push("/generate")} variant="ghost">
              Upload Another
            </AnimatedButton>
            <AnimatedButton onClick={() => setExportModalOpen(true)} variant="primary">
              Export Docs
            </AnimatedButton>
          </div>
        </div>

        <DocTabs 
          activeTab={activeTab} 
          onChange={setActiveTab} 
          availableDocs={availableDocs} 
        />

        <motion.div
          key={activeTab}
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.3 }}
        >
          {renderContent()}
        </motion.div>
      </motion.div>
    </div>
  );
}
